#!/usr/bin/env python3
"""Bundle ordered local CSS without changing its cascade or source files.

    python scripts/build_styles.py          # validate and show the plan
    python scripts/build_styles.py --write  # generate bundles and update HTML
    python scripts/build_styles.py --check  # require up-to-date output

styles-manifest.json is the durable source of each page's stylesheet order,
including after the original links have been replaced. Add new pages or styles
there deliberately. fonts.css remains a separate, unmodified HTML link.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "scripts/styles-manifest.json"
MARKER = "/* Generated by scripts/build_styles.py. Edit the source stylesheets. */"


@dataclass
class Link:
    start: int
    end: int
    attrs: dict[str, str | None]


class PageLinks(HTMLParser):
    def __init__(self, text: str):
        super().__init__(convert_charrefs=True)
        self.offsets = [0]
        for match in re.finditer("\n", text):
            self.offsets.append(match.end())
        self.stylesheets: list[Link] = []
        self.inline_styles: list[int] = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        line, column = self.getpos()
        start = self.offsets[line - 1] + column
        if tag == "style":
            self.inline_styles.append(start)
        attributes = dict(attrs)
        if tag != "link" or "stylesheet" not in (attributes.get("rel") or "").lower().split():
            return
        if len(attributes) != len(attrs):
            raise ValueError("Duplicate stylesheet link attributes are unsupported")
        self.stylesheets.append(Link(start, start + len(self.get_starttag_text()), attributes))

    handle_startendtag = handle_starttag


def local_path(value: str) -> str:
    url = urlsplit(value)
    if url.scheme or url.netloc or not url.path.startswith("/") or url.fragment:
        raise ValueError(f"Expected a root-relative local stylesheet, got {value!r}")
    return unquote(url.path.lstrip("/"))


def safe_file(root: Path, name: str, suffix: str) -> Path:
    if not re.fullmatch(r"[A-Za-z0-9_./-]+", name) or Path(name).is_absolute() or ".." in Path(name).parts:
        raise ValueError(f"Unsafe manifest path: {name!r}")
    path = root / name
    if path.suffix != suffix or not path.is_file() or not path.resolve().is_relative_to(root):
        raise ValueError(f"Missing or unsupported source file: {name}")
    return path


def read_css(root: Path, name: str) -> str:
    css = safe_file(root, name, ".css").read_text(encoding="utf-8")
    # Imports, namespaces and encoding declarations need separate handling; do
    # not silently alter their meaning by concatenating files.
    inspected = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    if re.search(r"@(import|charset|namespace)\b", inspected, re.I):
        raise ValueError(f"{name}: @import/@charset/@namespace requires explicit handling")
    urls = re.compile(r"url\(\s*(?:\"([^\"]*)\"|'([^']*)'|([^)'\"]*))\s*\)", re.I)
    matches = list(urls.finditer(inspected))
    if len(matches) != len(re.findall(r"\burl\s*\(", inspected, re.I)):
        raise ValueError(f"{name}: an unsupported CSS url() must be reviewed")
    for match in matches:
        value = next(part for part in match.groups() if part is not None).strip()
        if value.startswith(("data:", "#")):
            continue
        if not value.startswith("/") or value.startswith("//"):
            raise ValueError(f"{name}: use root-relative assets before bundling: {value!r}")
        resource = unquote(urlsplit(value).path.lstrip("/"))
        if not (root / resource).is_file():
            raise ValueError(f"{name}: missing local CSS resource: {resource}")
    return css


def render_page(text: str, page: str, sources: list[str], font: str,
                output_dir: str, identity: str, href: str) -> str:
    parsed = PageLinks(text)
    owned: list[Link] = []
    original: list[str] = []
    font_links: list[Link] = []
    bundled = False
    bundle_pattern = re.compile(re.escape(output_dir) + r"/bundle-([0-9a-f]{12})\.css")
    for link in parsed.stylesheets:
        attributes = link.attrs
        path = local_path(attributes.get("href") or "")
        if path == font:
            font_links.append(link)
            continue
        marker = attributes.get("data-style-bundle")
        match = bundle_pattern.fullmatch(path)
        if marker and match and marker == match.group(1):
            if bundled:
                raise ValueError(f"{page}: multiple generated bundles")
            bundled = True
        elif path in sources and marker is None:
            original.append(path)
        else:
            raise ValueError(f"{page}: unknown stylesheet {path!r}; update the manifest explicitly")
        allowed = {"rel", "href", "type", "media", "data-style-bundle"}
        if (set(attributes) - allowed or attributes.get("rel", "").lower() != "stylesheet"
                or attributes.get("type", "text/css") != "text/css"
                or attributes.get("media", "all") != "all"):
            raise ValueError(f"{page}: stylesheet attributes need explicit handling: {attributes}")
        owned.append(link)
    if len(font_links) != 1 or not owned:
        raise ValueError(f"{page}: expected one font stylesheet and at least one page stylesheet")
    if bundled and original:
        raise ValueError(f"{page}: mixed source and generated stylesheet links")
    if not bundled and original != sources:
        raise ValueError(f"{page}: stylesheet order differs from manifest: {original}")
    if font_links[0].start > owned[0].start:
        raise ValueError(f"{page}: fonts.css must precede the page styles to preserve order")
    if any(owned[0].start < position < owned[-1].end for position in parsed.inline_styles):
        raise ValueError(f"{page}: interleaved inline styles prevent safe concatenation")
    replacement = f'<link rel="stylesheet" href="{href}" data-style-bundle="{identity}">'
    for index in range(len(owned) - 1, -1, -1):
        link = owned[index]
        text = text[:link.start] + (replacement if index == 0 else "") + text[link.end:]
    return text


def build(root: Path, mode: str) -> None:
    manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    if manifest.get("version") != 1:
        raise ValueError("Unsupported styles manifest version")
    pages = manifest["pages"]
    excluded = set(manifest["exclude_dirs"])
    found = {path.relative_to(root).as_posix() for path in root.rglob("*.html")
             if not set(path.relative_to(root).parts).intersection(excluded)}
    if found != set(pages):
        raise ValueError(f"Manifest page mismatch; unlisted={sorted(found-set(pages))}, missing={sorted(set(pages)-found)}")
    output_dir = manifest["output_dir"]
    if output_dir != "assets/styles":
        raise ValueError("Only the owned assets/styles output directory is supported")
    font = manifest["font_stylesheet"]
    safe_file(root, font, ".css")
    bundles: dict[str, bytes] = {}
    changes: dict[Path, tuple[bytes, bytes]] = {}
    css_cache: dict[str, str] = {}
    for page, sources in pages.items():
        if not sources or len(sources) != len(set(sources)) or font in sources:
            raise ValueError(f"{page}: invalid or duplicate source order")
        identity = hashlib.sha256("\n".join(sources).encode()).hexdigest()[:12]
        parts = [MARKER + "\n"]
        for source in sources:
            if source not in css_cache:
                css_cache[source] = read_css(root, source)
            parts.append(f"\n/* Source: {source} */\n" + css_cache[source] + "\n")
        payload = "".join(parts).encode("utf-8")
        filename = f"{output_dir}/bundle-{identity}.css"
        if filename in bundles and bundles[filename] != payload:
            raise ValueError("Bundle identity collision")
        bundles[filename] = payload
        content_hash = hashlib.sha256(payload).hexdigest()[:12]
        href = f"/{filename}?v={content_hash}"
        path = safe_file(root, page, ".html")
        before = path.read_bytes()
        after = render_page(before.decode("utf-8"), page, sources, font,
                            output_dir, identity, href).encode("utf-8")
        changes[path] = (before, after)

    stale_bundles = [name for name, data in bundles.items()
                     if not (root / name).is_file() or (root / name).read_bytes() != data]
    changed_pages = [path for path, (before, after) in changes.items() if before != after]
    print(f"{len(pages)} pages → {len(bundles)} shared bundles; each page keeps one separate font stylesheet.")
    print(f"{len(changed_pages)} HTML updates; {len(stale_bundles)} bundle writes.")
    if mode == "check":
        if stale_bundles or changed_pages:
            raise ValueError("Styles are stale; run scripts/build_styles.py --write")
        print("All stylesheet links, bundle content and cache hashes are current.")
    elif mode == "write":
        # Complete validation above before mutating any HTML or output.
        if any(path.read_bytes() != before for path, (before, _) in changes.items()):
            raise ValueError("An HTML file changed during planning; rerun after edits finish")
        (root / output_dir).mkdir(parents=True, exist_ok=True)
        for name in stale_bundles:
            path = root / name
            temporary = path.with_suffix(".css.tmp")
            temporary.write_bytes(bundles[name])
            temporary.replace(path)
        for path in changed_pages:
            temporary = path.with_suffix(".html.tmp")
            temporary.write_bytes(changes[path][1])
            temporary.replace(path)
        print("Generated bundles and stylesheet links updated. Source CSS and font links are unchanged.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument("--write", action="store_true")
    actions.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT, help="Alternate site root for an isolated build check")
    args = parser.parse_args()
    try:
        build(args.root.resolve(), "write" if args.write else "check" if args.check else "plan")
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as error:
        print(f"Styles build stopped: {error}", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
